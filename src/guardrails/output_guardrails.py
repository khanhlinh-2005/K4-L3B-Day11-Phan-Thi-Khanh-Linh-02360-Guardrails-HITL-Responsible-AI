# Implement content_filter()
# ============================================================

def content_filter(response: str) -> dict:
    """Filter response for PII, secrets, and sensitive content.

    Args:
        response: The LLM's response text.

    Returns:
        dict with:
            - safe: True/False
            - issues: list of detected problems
            - redacted: cleaned response
    """

    issues = []
    redacted = response

    # --------------------------------------------------------
    # Patterns
    # --------------------------------------------------------
    PII_PATTERNS = {
        # Vietnamese phone number
        "phone": r"\b0\d{9,10}\b",

        # Email address
        "email": r"\b[\w.-]+@[\w.-]+\.[a-zA-Z]{2,}\b",

        # Vietnamese CMND / CCCD
        "national_id": r"\b(?:\d{9}|\d{12})\b",

        # OpenAI-style API key
        "api_key": r"\bsk-[a-zA-Z0-9_-]+\b",

        # Generic password patterns:
        # password: xxx
        # password=xxx
        # password is xxx
        "password": (
            r"\bpassword\s*(?:[:=]|\bis\b)\s*\S+"
        ),

        # Common secret/token patterns
        "secret": (
            r"\b(?:secret|token|access[_ -]?token)"
            r"\s*(?:[:=]|\bis\b)\s*\S+"
        ),
    }

    # --------------------------------------------------------
    # Detect + redact
    # --------------------------------------------------------
    for name, pattern in PII_PATTERNS.items():
        matches = re.findall(
            pattern,
            response,
            flags=re.IGNORECASE,
        )

        if matches:
            issues.append(f"{name}: {len(matches)} found")

            redacted = re.sub(
                pattern,
                "[REDACTED]",
                redacted,
                flags=re.IGNORECASE,
            )

    return {
        "safe": len(issues) == 0,
        "issues": issues,
        "redacted": redacted,
    }


